#!/usr/bin/env python3
"""Generate components/imx477/imx477_regs.h from the Raspberry Pi Linux imx477 driver.

The register addresses and values are hardware facts about the Sony IMX477. This script
reads them out of the Linux driver source (raspberrypi/linux,
drivers/media/i2c/imx477.c) and writes them as plain C tables for the ESP32 driver.
No driver code is reused.

Usage:
    curl -LO https://raw.githubusercontent.com/raspberrypi/linux/rpi-6.6.y/drivers/media/i2c/imx477.c
    python3 gen_imx477_regs.py imx477.c ../components/imx477/imx477_regs.h
"""
import re
import sys

TABLES = {
    'mode_common_regs': 'imx477_common_regs',
    'link_450Mhz_regs': 'imx477_link_450mhz_regs',
    'mode_2028x1080_regs': 'imx477_mode_2028x1080_regs',
    'mode_2028x1520_regs': 'imx477_mode_2028x1520_regs',
    'mode_4056x3040_regs': 'imx477_mode_4056x3040_regs',
}


def extract(src, name):
    m = re.search(r'static const struct imx477_reg ' + re.escape(name) + r'\[\]\s*=\s*\{(.*?)\n\};', src, re.S)
    if not m:
        raise SystemExit('table %s not found' % name)
    pairs = re.findall(r'\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*\}', m.group(1))
    return [(int(a, 16), int(v, 16)) for a, v in pairs]


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    src = open(sys.argv[1]).read()
    out = ['// Generated by esp32/tools/gen_imx477_regs.py. Do not edit by hand.',
           '// Sony IMX477 register settings (addresses and values) as used by the',
           '// Raspberry Pi HQ Camera. 24 MHz XCLK, 2-lane CSI-2, 450 MHz link (900 Mbit/s per lane).',
           '#pragma once', '#include <stdint.h>', '#include <stddef.h>', '',
           'typedef struct { uint16_t addr; uint8_t val; } imx477_reg_t;', '']
    for linux_name, c_name in TABLES.items():
        regs = extract(src, linux_name)
        out.append('static const imx477_reg_t %s[] = {' % c_name)
        for i in range(0, len(regs), 4):
            out.append('    ' + ' '.join('{0x%04x, 0x%02x},' % r for r in regs[i:i + 4]))
        out.append('};')
        out.append('#define %s_LEN (sizeof(%s) / sizeof(%s[0]))' % (c_name.upper(), c_name, c_name))
        out.append('')
    open(sys.argv[2], 'w').write('\n'.join(out))
    print('wrote', sys.argv[2])


if __name__ == '__main__':
    main()
